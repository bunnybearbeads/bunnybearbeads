/**
 * Экспорт мастер-данных в публичные данные сайта.
 *
 * Мастер-данные лежат в `data/` — это симлинк на папку в Dropbox, в git она не попадает.
 * Там у каждого товара есть список штук (`items`) со служебными полями: id, даты, заметки для себя,
 * и комментарии для посетителей к точкам (`locationNotes`).
 * Сайт собирается в GitHub Actions, где Dropbox не виден, поэтому сборка читает только
 * публичную выжимку в `src/content/`: штуки свёрнуты в количество по точкам, а `memo`,
 * `soldAt`, проданные штуки и id наружу не уходят.
 *
 * Запускается сам при `astro dev` и `astro build` (интеграция в astro.config.mjs), в dev ещё и
 * следит за `data/`. Без `data/` (например, в GitHub Actions) ничего не делает: берутся
 * закоммиченные файлы. Вручную: `npm run export-data`.
 */
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA_DIR = path.join(ROOT, 'data');
const COLLECTIONS = ['products', 'families'];

/** Порядок точек в данных и на сайте. Должен совпадать с src/config/locations.ts */
const LOCATION_ORDER = ['dalat', 'ngay-mai', 'cat-food'];

const GENERATED_NOTE = 'Generated by scripts/export-data.mjs from data/. Do not edit: changes will be overwritten.';

async function readJsonDir(dir) {
  const files = (await fsp.readdir(dir)).filter((f) => f.endsWith('.json')).sort();
  const entries = [];
  for (const file of files) {
    const fullPath = path.join(dir, file);
    try {
      entries.push({ id: file.slice(0, -5), file: fullPath, data: JSON.parse(await fsp.readFile(fullPath, 'utf8')) });
    } catch (error) {
      throw new Error(`${fullPath}: ${error.message}`);
    }
  }
  return entries;
}

/**
 * Штуки товара → наличие по точкам. Проданные штуки и служебные поля отбрасываются.
 * К точке добавляется её комментарий из `locationNotes`, если там есть непроданные штуки.
 */
function toStock(product, seenIds, logger) {
  const { id: slug, data } = product;
  const items = data.items ?? [];
  const locationNotes = data.locationNotes ?? {};
  const quantities = new Map();

  items.forEach((item, index) => {
    const where = `product "${slug}", items[${index}]`;
    if (!item.id) throw new Error(`${where}: id is required`);
    const owner = seenIds.get(item.id);
    if (owner) throw new Error(`${where}: duplicate item id "${item.id}" (also in "${owner}")`);
    seenIds.set(item.id, slug);
    if (!LOCATION_ORDER.includes(item.location)) {
      throw new Error(`${where}: unknown location "${item.location}"`);
    }
    if (item.soldAt) return;
    quantities.set(item.location, (quantities.get(item.location) ?? 0) + 1);
  });

  for (const locationId of Object.keys(locationNotes)) {
    if (!LOCATION_ORDER.includes(locationId)) {
      throw new Error(`product "${slug}", locationNotes: unknown location "${locationId}"`);
    }
    if (!quantities.has(locationId)) {
      logger.warn(`product "${slug}": note for "${locationId}" is not shown, no unsold items there`);
    }
  }

  return LOCATION_ORDER.filter((id) => quantities.has(id)).map((locationId) => ({
    locationId,
    quantity: quantities.get(locationId),
    ...locationNotes[locationId],
  }));
}

function toPublicProduct(product, seenIds, logger) {
  const { items: _items, locationNotes: _locationNotes, ...rest } = product.data;
  return { $comment: GENERATED_NOTE, ...rest, stock: toStock(product, seenIds, logger) };
}

function toPublicFamily(family) {
  return { $comment: GENERATED_NOTE, ...family.data };
}

/** Пишет файл, только если содержимое изменилось — иначе dev-сервер перезагружается зря */
async function writeIfChanged(file, data) {
  const content = `${JSON.stringify(data, null, 2)}\n`;
  const current = await fsp.readFile(file, 'utf8').catch(() => null);
  if (current === content) return false;
  await fsp.writeFile(file, content);
  return true;
}

/**
 * Экспортирует data/ в src/content/. Возвращает false, если data/ нет.
 * Падает с понятной ошибкой, если в мастер-данных что-то не так.
 */
export async function exportData(logger = console) {
  if (!fs.existsSync(path.join(DATA_DIR, 'products'))) {
    logger.info('data/ not found, using committed src/content/');
    return false;
  }

  const seenIds = new Map();
  let changed = 0;

  for (const collection of COLLECTIONS) {
    const sourceDir = path.join(DATA_DIR, collection);
    const outDir = path.join(ROOT, 'src/content', collection);
    await fsp.mkdir(outDir, { recursive: true });

    const entries = fs.existsSync(sourceDir) ? await readJsonDir(sourceDir) : [];
    const toPublic = collection === 'products'
      ? (entry) => toPublicProduct(entry, seenIds, logger)
      : toPublicFamily;

    for (const entry of entries) {
      if (await writeIfChanged(path.join(outDir, `${entry.id}.json`), toPublic(entry))) changed += 1;
    }

    // Удалённые из мастер-данных — удаляем и из публичных
    const keep = new Set(entries.map((e) => `${e.id}.json`));
    for (const file of await fsp.readdir(outDir)) {
      if (file.endsWith('.json') && !keep.has(file)) {
        await fsp.unlink(path.join(outDir, file));
        changed += 1;
      }
    }
  }

  logger.info(changed ? `exported data/ → src/content/ (${changed} file(s) changed)` : 'src/content/ is up to date with data/');
  return true;
}

/**
 * Следит за data/ в dev и переэкспортирует при изменениях.
 * Astro перезапускает сервер внутри того же процесса (например, после правки конфига),
 * поэтому прежний наблюдатель закрываем — иначе остаётся старый со старым кодом экспорта.
 */
export function watchData(logger = console) {
  globalThis.__productDataWatcher?.close();
  if (!fs.existsSync(DATA_DIR)) return;
  let timer;
  // Симлинк: следим за настоящей папкой в Dropbox
  globalThis.__productDataWatcher = fs.watch(fs.realpathSync(DATA_DIR), { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      exportData(logger).catch((error) => logger.error(error.message));
    }, 200);
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  exportData().catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
