/**
 * AI: Состояние воспроизведения видео в галерее.
 *
 * Хранит контекст взаимодействия пользователя с конкретным слайдом:
 * 1. `userPaused` — поставил ли пользователь видео на паузу вручную (кликом/тапом).
 *    Если `false` — при переходе на этот слайд видео запускается автоматически.
 *    Если `true` — при возвращении на слайд видео остаётся на паузе.
 * 2. `hasControls` — отображаются ли нативные контролы плеера. На смартфонах
 *    изначально false (чтобы iOS Safari не рисовал темный оверлей), после первого тапа — true.
 * 3. `currentTime` — текущая секунда воспроизведения, предотвращает сброс видео на начало (0:00)
 *    при перелистывании слайдов (виртуализации PhotoSwipe) и переходе между страницей и лайтбоксом.
 */
export interface VideoPlaybackState {
  userPaused: boolean;
  hasControls: boolean;
  currentTime: number;
}

